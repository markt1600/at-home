import fs from 'node:fs';
import {createHouseModel} from './house-model.mjs';
import {HOUSE_ROOMS,HOUSE_VIEWS,floorHeight,pointInPolygon} from '../src/house-layout.js';
import {inWalkableArea} from '../src/navigation.js';

// Export the actual collision geometry, keeping the editor independent of Three.js.
// Regenerated before every build so furniture edits also update memory placement.
const world=createHouseModel({optimize:false}),round=n=>Math.round(n*1e5)/1e5;
const obstacles=world.colliders.map(c=>Object.fromEntries(Object.entries(c).map(([k,v])=>[k,typeof v==='number'?round(v):v])));
const furniture=obstacles.filter(c=>!c.wall&&!(c.d<=.18&&c.top===.45));
const step=.1,start=HOUSE_VIEWS.hall,queue=[[Math.round(start[0]/step),Math.round(start[2]/step)]],seen=new Set([queue[0].join(',')]),open=[];
const distance=(x,z,c)=>{const dx=x-c.x,dz=z-c.z,a=c.angle||0;return Math.hypot(Math.max(0,Math.abs(dx*Math.cos(a)-dz*Math.sin(a))-c.w/2),Math.max(0,Math.abs(dx*Math.sin(a)+dz*Math.cos(a))-c.d/2));};
for(let n=0;n<queue.length;n++){
 const [ix,iz]=queue[n],x=round(ix*step),z=round(iz*step),y=floorHeight(x,z);
 const room=HOUSE_ROOMS.find(r=>r.walkable!==false&&pointInPolygon(x,z,r.polygon));
 if(room&&!obstacles.some(c=>!(c.top!==undefined&&c.top<=y+.015)&&distance(x,z,c)<(c.wall?.22:.45)))open.push([x,round(y),z,room.id]);
 for(const [dx,dz] of [[1,0],[-1,0],[0,1],[0,-1]]){
  const nx=ix+dx,nz=iz+dz,key=nx+','+nz;if(seen.has(key))continue;
  if(!inWalkableArea(nx*step,nz*step,true,world.colliders)||Math.abs(floorHeight(nx*step,nz*step)-y)>.12)continue;
  seen.add(key);queue.push([nx,nz]);
 }
}
const target=new URL('../src/memory-floor-geometry.js',import.meta.url);
fs.writeFileSync(target,'// Generated by scripts/export-memory-floor-plan.mjs from the game geometry.\n'+
 `export const MEMORY_OBSTACLES=${JSON.stringify(obstacles)};\n`+
 `export const MEMORY_FURNITURE=${JSON.stringify(furniture)};\n`+
 `export const MEMORY_OPEN_SPOTS=${JSON.stringify(open)};\n`);
console.log(`Memory floor plan: ${furniture.length} furniture footprints, ${open.length} reachable clear positions.`);
